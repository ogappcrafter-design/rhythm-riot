// Generates iPhone/iPad Home Screen launch screens (apple-touch-startup-image) into public/splash/
// and writes the matching <link> tags into index.html between the ios-splash markers.
// iOS only shows a launch image whose size EXACTLY matches the device, so every screen size is listed.
// Usage: node scripts/make-ios-splash.mjs   (CHROME_PATH overrides the Chromium binary)
import pkg from 'playwright-core';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'splash');
const CHROME = process.env.CHROME_PATH || '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome';

// [css width, css height, pixel ratio] — portrait.
const DEVICES = [
  [440, 956, 3], // 16 Pro Max, 17 Pro Max
  [430, 932, 3], // 14 Pro Max, 15 Plus/Pro Max, 16 Plus
  [420, 912, 3], // iPhone Air
  [428, 926, 3], // 12/13 Pro Max, 14 Plus
  [414, 896, 3], // XS Max, 11 Pro Max
  [414, 896, 2], // XR, 11
  [402, 874, 3], // 16 Pro, 17, 17 Pro
  [393, 852, 3], // 14 Pro, 15, 15 Pro, 16
  [390, 844, 3], // 12, 13, 14, 16e
  [375, 812, 3], // X, XS, 11 Pro, 12/13 mini
  [414, 736, 3], // 6+/7+/8 Plus
  [375, 667, 2], // 6/7/8, SE 2nd/3rd gen
  [320, 568, 2], // SE 1st gen
  [1032, 1376, 2], // iPad Pro 13 (M4)
  [1024, 1366, 2], // iPad Pro 12.9
  [834, 1210, 2], // iPad Pro 11 (M4)
  [834, 1194, 2], // iPad Pro 11
  [820, 1180, 2], // iPad Air / 10th gen
  [834, 1112, 2], // iPad Air 3 / Pro 10.5
  [810, 1080, 2], // iPad 7th-9th gen
  [768, 1024, 2], // iPad mini 5 / older
  [744, 1133, 2], // iPad mini 6+
];

mkdirSync(OUT, { recursive: true });
const b = await pkg.chromium.launch({ executablePath: CHROME, args: ['--no-sandbox'] });
const tags = [];
for (const [w, h, dpr] of DEVICES) {
  const p = await b.newPage({ viewport: { width: w, height: h }, deviceScaleFactor: dpr });
  await p.goto('file://' + join(ROOT, 'scripts', 'ios-splash-template.html'), { waitUntil: 'load' });
  await p.evaluate(async () => { await document.fonts.ready; });
  const name = `${w * dpr}x${h * dpr}.jpg`;
  await p.screenshot({ path: join(OUT, name), type: 'jpeg', quality: 86 });
  await p.close();
  tags.push(
    `    <link rel="apple-touch-startup-image" href="./splash/${name}" media="(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: portrait)" />`,
  );
}
await b.close();

const idx = join(ROOT, 'index.html');
const html = readFileSync(idx, 'utf8');
const block = `<!-- ios-splash:start (generated by scripts/make-ios-splash.mjs) -->\n${tags.join('\n')}\n    <!-- ios-splash:end -->`;
const out = /<!-- ios-splash:start[\s\S]*?ios-splash:end -->/.test(html)
  ? html.replace(/<!-- ios-splash:start[\s\S]*?ios-splash:end -->/, block)
  : html.replace('<meta name="apple-mobile-web-app-title" content="Rhythm Riot" />', `<meta name="apple-mobile-web-app-title" content="Rhythm Riot" />\n    ${block}`);
writeFileSync(idx, out);
console.log(`wrote ${DEVICES.length} launch screens + tags`);
