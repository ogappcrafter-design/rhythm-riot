#!/usr/bin/env node
/**
 * Rhythm Riot — build-time chart generator (spec Section 5.2).
 *
 * Reads the librosa analysis for each launch track and synthesizes deterministic,
 * musically-plausible charts for Easy / Medium / Hard, plus a scaffolded 5-lane Expert.
 * Output: src/charts/<trackId>.json  (committed; NOT computed on-device).
 *
 * The source analysis captured tempo, duration, onset density and energy statistics but
 * not the full onset list, so charts are built on a tempo-derived beat grid whose note
 * placement is weighted by a synthesized energy curve. Everything is seeded, so re-running
 * this script reproduces byte-identical charts.
 *
 * Expert charts are marked { autoGenerated: true } — per spec 5.3 they are meant to be
 * hand-passed by ear before shipping as "final" Expert content. They are unlocked-gated,
 * so they are safe to ship as scaffolding in v1.
 *
 * Run:  node scripts/generateCharts.mjs   (also runs automatically on `npm run build`)
 */

