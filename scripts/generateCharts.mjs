#!/usr/bin/env node
/**
 * Rhythm Riot — chart generator (spec Section 5.2).
 *
 * Consumes REAL librosa analysis (scripts/analysis_real.json, produced by scripts/analyze.py)
 * and turns each track's actual onset list + energy envelope into committed per-track chart
 * JSON for Easy / Medium / Hard, plus a scaffolded 5-lane Expert. Charts are a build-time
 * asset — never computed on-device (spec 5.2 / 9).
 *
 * Note placement is now anchored to detected onsets (not a synthesized grid):
 *   - Easy   : onsets snapped to the beat grid, strongest kept, ~50% of onsets, >=250ms apart
 *   - Medium : strongest ~75% of onsets, 4 lanes
 *   - Hard   : ~100% of onsets incl. sub-beat syncopation, 4 lanes, tight spacing
 *   - Expert : Hard's onset set + energy-driven flourishes on drops, 5 lanes (autoGenerated —
 *              meant to be hand-passed by ear before shipping as "final", spec 5.3)
 *
 * Lane assignment and flourishes are seeded → regeneration is byte-identical (enforced by test).
 * If scripts/analysis_real.json is missing, run `python3 scripts/analyze.py` first.
 *
 * Run:  node scripts/generateCharts.mjs   (also runs automatically on `npm run build`)
 */

import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = join(__dirname, '..', 'src', 'charts');
const ANALYSIS_PATH = join(__dirname, 'analysis_real.json');

const TRACKS = [
  { id: 'i_dont_care_tonight', title: "I Don't Care Tonight", audioFile: 'i_dont_care_tonight.mp3' },
  { id: 'where_the_inside_opens_wide', title: 'Where the Inside Opens Wide', audioFile: 'where_the_inside_opens_wide.mp4' },
  { id: 'who_moved_the_moon', title: 'Who Moved the Moon', audioFile: 'who_moved_the_moon.mp4' },
  { id: 'dub_steps_trip', title: 'Dub Steps Trip', audioFile: 'dub_steps_trip.mp4' },
  { id: 'everyday_g', title: 'Everyday G', audioFile: 'everyday_g.mp4' },
];

const HIT_WINDOWS = {
  easy: { perfect: 120, great: 200, good: 280 },
  medium: { perfect: 100, great: 170, good: 240 },
  hard: { perfect: 80, great: 140, good: 200 },
  expert: { perfect: 60, great: 110, good: 160 },
};

const DIFF_CONFIG = {
  easy: { laneCount: 3, onsetFraction: 0.5, minSpacingMs: 250, snapToBeat: true, holdFraction: 0.26 },
  medium: { laneCount: 4, onsetFraction: 0.75, minSpacingMs: 170, snapToBeat: false, holdFraction: 0.26 },
  hard: { laneCount: 4, onsetFraction: 1.0, minSpacingMs: 105, snapToBeat: false, holdFraction: 0.24 },
  expert: { laneCount: 5, onsetFraction: 1.0, minSpacingMs: 85, snapToBeat: false, holdFraction: 0.26 },
};

// Hold-note tuning (spec 5.4 "hold" type). A note becomes a hold where the SONG ITSELF sustains:
// we read the RMS energy envelope and only place a hold where energy stays up after the hit
// (a pad / held note / sustained synth), with the hold's LENGTH matching how long it sustains.
// The tail always ends a hair before the next note in the SAME lane, so a hold can span other
// lanes' notes but never doubles up in its own lane.
const HOLD_RELEASE_BUFFER_MS = 120; // tail ends this far before the next same-lane note
const HOLD_MIN_MS = 320; // shorter than this isn't worth being a hold
const HOLD_CAP_MS = 3200; // never longer than this
const SUSTAIN_DROP_FRAC = 0.62; // sustain "ends" when energy falls below this fraction of its attack peak
const SUSTAIN_FLOOR = 0.16; // ...or below this absolute (normalized) energy
const ATTACK_STRENGTH = 0.5; // a hold can't extend past the next onset at/above this strength (a new struck note)

/* ------------------------------ RNG ------------------------------ */

function hashSeed(str) {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return h >>> 0;
}

function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* ------------------------ energy sampling ------------------------ */

function sampleEnvelope(env, tMs) {
  if (env.length === 0) return 0.3;
  if (tMs <= env[0].tMs) return env[0].e;
  const last = env[env.length - 1];
  if (tMs >= last.tMs) return last.e;
  for (let i = 1; i < env.length; i++) {
    if (tMs < env[i].tMs) {
      const a = env[i - 1];
      const b = env[i];
      const f = (tMs - a.tMs) / (b.tMs - a.tMs);
      return a.e + (b.e - a.e) * f;
    }
  }
  return last.e;
}

/* --------------------- note selection core ---------------------- */

// Snap onsets to the nearest beat, keeping the strongest onset per beat.
function snapToBeats(onsets, beatsMs) {
  if (beatsMs.length === 0) return onsets.slice();
  const byBeat = new Map();
  let bi = 0;
  for (const o of onsets) {
    // advance beat pointer to nearest beat
    while (bi < beatsMs.length - 1 && Math.abs(beatsMs[bi + 1] - o.tMs) <= Math.abs(beatsMs[bi] - o.tMs)) {
      bi++;
    }
    // (bi only moves forward; onsets are time-sorted so this is fine)
    const beatT = beatsMs[bi];
    const prev = byBeat.get(beatT);
    if (!prev || o.strength > prev.strength) {
      byBeat.set(beatT, { tMs: beatT, strength: o.strength, energy: o.energy });
    }
  }
  return [...byBeat.values()].sort((a, b) => a.tMs - b.tMs);
}

// Greedily accept the strongest notes that respect min spacing; cap at targetCount.
function selectNotes(candidates, targetCount, minSpacingMs) {
  const byStrength = [...candidates].sort((a, b) => b.strength - a.strength);
  const accepted = [];
  const acceptedTimes = [];
  const tooClose = (t) => {
    for (let i = 0; i < acceptedTimes.length; i++) {
      if (Math.abs(acceptedTimes[i] - t) < minSpacingMs) return true;
    }
    return false;
  };
  for (const c of byStrength) {
    if (accepted.length >= targetCount) break;
    if (tooClose(c.tMs)) continue;
    accepted.push(c);
    acceptedTimes.push(c.tMs);
  }
  accepted.sort((a, b) => a.tMs - b.tMs);
  return accepted;
}

// Energy-clustered lane wander that stays playable. Returns notes carrying lane + energy so
// hold marking (which needs same-lane gaps) can run afterward.
function assignLanes(trackId, diff, notes, laneCount) {
  const rng = mulberry32(hashSeed(`${trackId}::${diff}::lanes`));
  let lane = Math.floor(rng() * laneCount);
  let repeat = 0;
  return notes.map((n) => {
    const spread = 1 + Math.floor((n.energy ?? 0.4) * (laneCount - 1));
    let next;
    let guard = 0;
    do {
      const dir = rng() < 0.5 ? -1 : 1;
      const step = 1 + Math.floor(rng() * spread);
      next = Math.max(0, Math.min(laneCount - 1, lane + dir * step));
      guard++;
    } while (next === lane && repeat >= 1 && guard < 6);
    if (next === lane) repeat++;
    else repeat = 0;
    lane = next;
    return { timeMs: n.tMs, lane, energy: n.energy ?? 0.4, type: 'tap' };
  });
}

// Place holds on sustained parts of the song (see tuning above). Mutates notes (type + holdMs).
function markHolds(trackId, diff, notes, analysis) {
  const cfg = DIFF_CONFIG[diff];
  const rng = mulberry32(hashSeed(`${trackId}::${diff}::holds`));

  // For each note, find the next note in the same lane.
  const nextSameLane = new Array(notes.length).fill(-1);
  const lastByLane = {};
  for (let i = notes.length - 1; i >= 0; i--) {
    const lane = notes[i].lane;
    if (lastByLane[lane] !== undefined) nextSameLane[i] = lastByLane[lane];
    lastByLane[lane] = i;
  }

  const env = analysis.energyEnvelope;
  const onsets = analysis.onsets; // time-sorted, each { tMs, strength, energy }

  // Time of the next strong ATTACK after t — a held note ends when a new note is struck.
  const nextAttackAfter = (tMs) => {
    for (const o of onsets) {
      if (o.tMs > tMs + 320 && o.strength >= ATTACK_STRENGTH) return o.tMs;
    }
    return Infinity;
  };

  // How long the sound actually SUSTAINS after a note: the hold ends the moment the energy
  // fades below a fraction of its attack peak (for ~160ms, so a single noisy sample doesn't
  // cut it early) OR the next strong attack lands — whichever comes first, bounded by `room`.
  const sustainMsAt = (tMs, room) => {
    let peak = 0;
    for (let dt = 0; dt <= 350; dt += 90) peak = Math.max(peak, sampleEnvelope(env, tMs + dt));
    if (peak < 0.16) return 0; // too quiet to be a real held note
    const threshold = Math.max(SUSTAIN_DROP_FRAC * peak, SUSTAIN_FLOOR);

    let decayEnd = room;
    let firstBelow = -1;
    for (let tt = 200; tt <= room; tt += 70) {
      if (sampleEnvelope(env, tMs + tt) < threshold) {
        if (firstBelow < 0) firstBelow = tt;
        if (tt - firstBelow >= 160) {
          decayEnd = firstBelow; // the note faded here
          break;
        }
      } else {
        firstBelow = -1;
      }
    }
    // Don't hold across the next struck note.
    const attack = nextAttackAfter(tMs);
    const attackBound = attack === Infinity ? room : attack - tMs - 100;
    return Math.max(0, Math.min(decayEnd, attackBound, room));
  };

  const candidates = [];
  for (let i = 0; i < notes.length; i++) {
    const j = nextSameLane[i];
    const nextT = j < 0 ? analysis.durationMs : notes[j].timeMs;
    const room = Math.min(nextT - notes[i].timeMs - HOLD_RELEASE_BUFFER_MS, HOLD_CAP_MS);
    if (room < HOLD_MIN_MS) continue;
    const sustain = sustainMsAt(notes[i].timeMs, room);
    if (sustain < HOLD_MIN_MS) continue; // only where the music actually sustains
    candidates.push({ i, holdMs: sustain });
  }
  // Prefer the longest, most-sustained holds; slight seeded jitter to vary placement.
  candidates.sort((a, b) => b.holdMs - a.holdMs + (rng() - 0.5) * 120);

  const targetHolds = Math.round(notes.length * cfg.holdFraction);
  const lastHoldTimeByLane = {};
  let placed = 0;
  for (const c of candidates) {
    if (placed >= targetHolds) break;
    const n = notes[c.i];
    // Don't stack two holds too close in the same lane.
    const lastT = lastHoldTimeByLane[n.lane];
    if (lastT !== undefined && n.timeMs - lastT < 1200) continue;
    n.type = 'hold';
    n.holdMs = Math.round(c.holdMs);
    lastHoldTimeByLane[n.lane] = n.timeMs;
    placed++;
  }
}

// Strip internal fields and emit the committed note shape.
function finalizeNotes(notes) {
  return notes.map((n) => (n.type === 'hold' ? { timeMs: n.timeMs, lane: n.lane, type: 'hold', holdMs: n.holdMs } : { timeMs: n.timeMs, lane: n.lane, type: 'tap' }));
}

function buildDifficulty(trackId, diff, analysis) {
  const cfg = DIFF_CONFIG[diff];
  let candidates = analysis.onsets;
  if (cfg.snapToBeat) candidates = snapToBeats(analysis.onsets, analysis.beatsMs);
  const target = Math.round(analysis.numOnsets * cfg.onsetFraction);
  const picked = selectNotes(candidates, target, cfg.minSpacingMs);
  const notes = assignLanes(trackId, diff, picked, cfg.laneCount);
  markHolds(trackId, diff, notes, analysis);
  return finalizeNotes(notes);
}

// Expert: Hard's real-onset set (5-lane) + energy-driven flourishes on the hottest hits.
function buildExpert(trackId, analysis) {
  const cfg = DIFF_CONFIG.expert;
  const base = selectNotes(analysis.onsets, analysis.numOnsets, cfg.minSpacingMs);

  // Adaptive threshold: top ~20% by energy always yields flourish candidates.
  const energies = base.map((n) => n.energy).sort((a, b) => a - b);
  const threshold = energies.length ? energies[Math.floor(energies.length * 0.8)] : 0.8;

  const rng = mulberry32(hashSeed(`${trackId}::expert::flourish`));
  const beatMs = 60000 / analysis.bpm;
  const times = base.map((n) => n.tMs);
  const isFree = (t) => times.every((x) => Math.abs(x - t) >= cfg.minSpacingMs);

  const extras = [];
  for (const n of base) {
    if (n.energy >= threshold && rng() < 0.5) {
      const t2 = Math.round(n.tMs + beatMs / 4);
      if (t2 < analysis.durationMs && isFree(t2)) {
        extras.push({ tMs: t2, strength: n.strength, energy: n.energy });
        times.push(t2);
      }
    }
  }

  const all = [...base, ...extras].sort((a, b) => a.tMs - b.tMs);
  const notes = assignLanes(trackId, 'expert', all, cfg.laneCount);
  markHolds(trackId, 'expert', notes, analysis);
  return finalizeNotes(notes);
}

function buildMoodCurve(env, durationMs) {
  const sampleEveryMs = 2000;
  const samples = [];
  for (let t = 0; t <= durationMs; t += sampleEveryMs) {
    samples.push({ timeMs: t, energy: Number(sampleEnvelope(env, t).toFixed(3)) });
  }
  return samples;
}

/* ------------------------------ main ----------------------------- */

function generate() {
  if (!existsSync(ANALYSIS_PATH)) {
    console.error(`Missing ${ANALYSIS_PATH}. Run: python3 scripts/analyze.py`);
    process.exit(1);
  }
  const analysisAll = JSON.parse(readFileSync(ANALYSIS_PATH, 'utf8'));
  mkdirSync(OUT_DIR, { recursive: true });
  const summary = [];

  for (const track of TRACKS) {
    const a = analysisAll[track.id];
    if (!a) {
      console.error(`No analysis for ${track.id}`);
      process.exit(1);
    }

    const difficulties = {
      easy: { laneCount: 3, hitWindowMs: HIT_WINDOWS.easy, notes: buildDifficulty(track.id, 'easy', a), autoGenerated: true },
      medium: { laneCount: 4, hitWindowMs: HIT_WINDOWS.medium, notes: buildDifficulty(track.id, 'medium', a), autoGenerated: true },
      hard: { laneCount: 4, hitWindowMs: HIT_WINDOWS.hard, notes: buildDifficulty(track.id, 'hard', a), autoGenerated: true },
      expert: {
        laneCount: 5,
        hitWindowMs: HIT_WINDOWS.expert,
        unlockRequirement: { difficulty: 'hard', minPerfectPercent: 90 },
        notes: buildExpert(track.id, a),
        autoGenerated: true,
      },
    };

    const chart = {
      trackId: track.id,
      title: track.title,
      audioFile: track.audioFile,
      durationMs: a.durationMs,
      bpm: a.bpm,
      difficulties,
      moodCurve: {
        description:
          'Normalized 0-1 RMS energy at 2s sample points from real librosa analysis (scripts/analyze.py). Target arc for Vibe Score comparison (spec 4.4).',
        samples: buildMoodCurve(a.energyEnvelope, a.durationMs),
      },
    };

    writeFileSync(join(OUT_DIR, `${track.id}.json`), JSON.stringify(chart) + '\n');
    summary.push({
      id: track.id,
      easy: difficulties.easy.notes.length,
      medium: difficulties.medium.notes.length,
      hard: difficulties.hard.notes.length,
      expert: difficulties.expert.notes.length,
    });
  }

  writeFileSync(join(OUT_DIR, 'manifest.json'), JSON.stringify(TRACKS.map((t) => t.id)) + '\n');

  console.log('Generated charts from REAL onset analysis:');
  for (const s of summary) {
    console.log(`  ${s.id.padEnd(30)} easy=${s.easy} medium=${s.medium} hard=${s.hard} expert=${s.expert}`);
  }
  console.log(`Wrote ${summary.length} charts + manifest.json to src/charts/`);
}

generate();
